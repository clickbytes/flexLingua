/**
 * Dependency-free offline bundle for people opening index.html via file://.
 * This is a generated distribution artifact, NOT a second source of truth.
 * Run: node tools/build-standalone.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = [];
const moduleByPath = new Map();
const exportDeclaration = /^\s*export\s+(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;
const staticImport = /^\s*import\s*\{([\s\S]*?)\}\s*from\s*['"]([^'"]+)['"];?[ \t]*$/gm;

async function addModule(file) {
  const full = resolve(file);
  if (moduleByPath.has(full)) return moduleByPath.get(full);
  const relativePath = relative(join(root, 'js'), full);
  if (relativePath === '..' || relativePath.startsWith(`..${sep}`) ||
      isAbsolute(relativePath)) {
    throw new Error(`Unexpected module path: ${file}`);
  }
  let source = await readFile(full, 'utf8');
  const imports = [];
  source = source.replace(staticImport, (_, specifiers, from) => {
    const names = specifiers.split(',').map(s => s.trim()).filter(Boolean);
    if (!names.every(name => /^[A-Za-z_$][\w$]*(\s+as\s+[A-Za-z_$][\w$]*)?$/.test(name))) {
      throw new Error(`Unsupported module import in ${file}: ${specifiers}`);
    }
    imports.push({ names, from });
    return '';
  });
  // Keep module boundaries so any private top-level identifiers cannot collide.
  // Reserve the ID before walking dependencies, then emit in dependency-first order.
  const id = moduleByPath.size;
  moduleByPath.set(full, id);
  const dependencies = [];
  for (const spec of imports) {
    const dependency = resolve(dirname(full), spec.from);
    if (dependency === full) throw new Error(`Self import in ${file}`);
    dependencies.push({ id: await addModule(dependency), names: spec.names });
  }
  const exported = [...source.matchAll(exportDeclaration)].map(match => match[1]);
  source = source.replace(/^([ \t]*)export\s+(?=(?:const|let|var|function|class)\s)/gm, '$1');
  if (/\bexport\b|\bimport\s*\(/.test(source)) throw new Error(`Unsupported module syntax in ${file}`);
  modules.push({ id, dependencies, source, exported });
  return id;
}

const entryId = await addModule(join(root, 'js', 'main.js'));
const jsonPaths = [
  './data/concepts.json', './data/features.json', './data/en.json', './data/pl.json',
  './data/grammar/en.json', './data/grammar/pl.json', './data/tr.json', './data/grammar/tr.json',
  './data/morphology/features.json', './data/morphology/en.json', './data/morphology/pl.json'
];
const dictionary = Object.create(null);
for (const path of jsonPaths) {
  dictionary[path] = JSON.parse(await readFile(join(root, path), 'utf8'));
}
// Escape '<' because values are embedded inside a HTML <script> element.
const inlineDictionary = JSON.stringify(dictionary).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const compiled = [
  '/* Auto-generated by tools/build-standalone.mjs. Do not edit this bundle. */',
  '"use strict";',
  `globalThis.__flexLinguaEmbeddedData = ${inlineDictionary};`,
  'const __flexModules = Object.create(null);',
  ...modules.map(({ id, dependencies, source, exported }) => {
    const refs = dependencies.map(dep => {
      const names = dep.names.map(name => name.replace(/\s+as\s+/, ': '));
      return `const { ${names.join(', ')} } = __flexModules[${dep.id}];`;
    }).join('\n');
    return `__flexModules[${id}] = (() => {\n${refs}\n${source}\nreturn { ${exported.join(', ')} };\n})();`;
  }),
  `void __flexModules[${entryId}];`
].join('\n');
let template = await readFile(join(root, 'index.html'), 'utf8');
const bootstrap = /<script id="flexlingua-bootstrap">[\s\S]*?<\/script>/;
if (!bootstrap.test(template)) throw new Error('Cannot locate application bootstrap in index.html');
template = template.replace(bootstrap, `<script id="flexlingua-standalone">\n${compiled}\n</script>`);
template = template.replace('<span class="chip">INTERLINGUA · 1.12 CORE + MORPH</span>',
  '<span class="chip">INTERLINGUA · OFFLINE 1.12</span>');
template = template.replace(/\r/g, '');
const output = join(root, 'index-standalone.html');
if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8').catch(() => '');
  if (template !== existing) {
    let offset = 0;
    while (offset < template.length && template[offset] === existing[offset]) offset++;
    const start = Math.max(0, offset - 40);
    const end = offset + 80;
    const line = template.slice(0, offset).split('\n').length;
    console.error(`Offline build is out of date at line ${line}: run node tools/build-standalone.mjs`);
    console.error(`Current: ${JSON.stringify(existing.slice(start, end))}`);
    console.error(`Built:   ${JSON.stringify(template.slice(start, end))}`);
    process.exitCode = 1;
  } else {
    console.log('Offline HTML bundle is up to date');
  }
} else {
  await writeFile(output, template, 'utf8');
  console.log(`Built index-standalone.html (${Buffer.byteLength(template)} bytes)`);
}
